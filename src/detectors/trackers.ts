export function isTrackerDomain(hostname: string): boolean {
  const clean = hostname.toLowerCase().replace(/^www\./, "");
  if (TRACKER_DOMAINS.has(clean)) return true;
  for (const t of TRACKER_DOMAINS) {
    if (clean.endsWith("." + t)) return true;
  }
  return false;
}
